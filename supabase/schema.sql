create table if not exists public.lojas (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  nome text not null,
  cor_primaria text default '#D7261E',
  cor_destaque text default '#FFD21F',
  logo text,
  criado_em timestamptz not null default now()
);

create table if not exists public.categorias (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  nome text not null,
  segmento text default 'geral'
);
create unique index if not exists categorias_nome_por_usuario on public.categorias (user_id, lower(nome));

create table if not exists public.produtos (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  loja_id bigint references public.lojas(id) on delete set null,
  sku text,
  ean text,
  nome text not null,
  nome_curto text,
  marca text,
  descricao text,
  categoria_id bigint references public.categorias(id) on delete set null,
  unidade text default 'un',
  preco numeric(12,2),
  atributos jsonb default '{}'::jsonb,
  imagem text,
  imagem_recortada text,
  ativo boolean default true,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);
create index if not exists produtos_usuario_ean on public.produtos (user_id, ean);
create index if not exists produtos_usuario_sku on public.produtos (user_id, sku);
create index if not exists produtos_usuario_nome on public.produtos (user_id, nome);

create table if not exists public.ofertas (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  produto_id bigint references public.produtos(id) on delete cascade,
  tipo text,
  regra jsonb default '{}'::jsonb,
  validade_inicio date,
  validade_fim date
);

create table if not exists public.preferencias (
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  chave text not null,
  valor jsonb,
  primary key (user_id, chave)
);

create table if not exists public.encartes (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  titulo text not null,
  loja_id bigint references public.lojas(id) on delete set null,
  documento jsonb not null,
  miniatura text,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);

create table if not exists public.modelos (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  nome text not null,
  documento jsonb not null,
  miniatura text,
  criado_em timestamptz not null default now()
);

-- ---------- Segurança: cada um só vê o que é seu ----------
do $$
declare t text;
begin
  foreach t in array array['lojas','categorias','produtos','ofertas','preferencias','encartes','modelos'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists "somente o dono" on public.%I', t);
    execute format(
      'create policy "somente o dono" on public.%I for all to authenticated
         using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()))', t);
  end loop;
end $$;

grant select, insert, update, delete on all tables in schema public to authenticated;
grant usage, select on all sequences in schema public to authenticated;

-- ---------- Fotos e artes ----------
-- Pasta pública para leitura (as fotos precisam aparecer no encarte e na exportação),
-- mas cada usuário só envia/apaga dentro da própria pasta (o id dele).
insert into storage.buckets (id, name, public)
values ('imagens', 'imagens', true)
on conflict (id) do update set public = true;

drop policy if exists "imagens: ver a propria pasta" on storage.objects;
create policy "imagens: ver a propria pasta" on storage.objects for select to authenticated
  using (bucket_id = 'imagens' and (storage.foldername(name))[1] = (select auth.uid())::text);

drop policy if exists "imagens: enviar na propria pasta" on storage.objects;
create policy "imagens: enviar na propria pasta" on storage.objects for insert to authenticated
  with check (bucket_id = 'imagens' and (storage.foldername(name))[1] = (select auth.uid())::text);

drop policy if exists "imagens: alterar na propria pasta" on storage.objects;
create policy "imagens: alterar na propria pasta" on storage.objects for update to authenticated
  using (bucket_id = 'imagens' and (storage.foldername(name))[1] = (select auth.uid())::text);

drop policy if exists "imagens: apagar da propria pasta" on storage.objects;
create policy "imagens: apagar da propria pasta" on storage.objects for delete to authenticated
  using (bucket_id = 'imagens' and (storage.foldername(name))[1] = (select auth.uid())::text);
